// ==== Тарифи преміум-доступу ====
// Єдине джерело правди для цін — і бекенд (виставлення рахунку, нарахування днів),
// і фронтенд (що показати на кнопках) мають орієнтуватись на це.
// Щоб змінити ціну/тривалість — досить поправити тут.
export const PRICING_TIERS = [
  {
    id: "month",
    title: "Місяць",
    stars: 50,
    days: 30,
    description: "Повний доступ до всіх розділів на 30 днів.",
  },
  {
    id: "year",
    title: "Рік",
    stars: 250,
    days: 365,
    description: "Повний доступ до всіх розділів на 365 днів.",
  },
  {
    id: "lifetime",
    title: "Назавжди",
    stars: 400,
    days: 36500, // умовно «назавжди» (100 років) — простіше зберігати як звичайну дату, ніж окремий null-кейс
    description: "Повний доступ до всіх розділів без обмеження в часі.",
  },
];

export function findTier(tierId) {
  return PRICING_TIERS.find((t) => t.id === tierId) || null;
}
